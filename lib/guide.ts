export function topicsFor(role: RoleKey): GuideTopic[] {
  return guideTopics.filter((t) => t.roles === "all" || t.roles.includes(role));
}

/** نص الدليل كاملاً للمساعد الذكي */
export function guideAsText(): string {
  return guideTopics
    .map((t) => {
      const where = t.where ? ` [/${t.where.portal}/${t.where.section}/]` : "";
      const who = t.roles === "all" ? "الجميع" : t.roles.join("، ");
      return `## ${t.title}${where}\nيخصّ: ${who}\n${t.summary}\n${t.steps.map((s) => `- ${s}`).join("\n")}${t.tips ? "\n" + t.tips.map((s) => `* ${s}`).join("\n") : ""}`;
    })
    .join("\n\n");
}

/** فهرس مختصر للدليل — للنماذج المجانية ذات الحدود الضيّقة؛ تقرأ التفاصيل بأداة read_guide */
export function guideIndex(): string {
  return guideTopics
    .map((t) => `${t.id}: ${t.title}${t.where ? ` [/${t.where.portal}/${t.where.section}/]` : ""} — ${t.summary}`)
    .join("\n");
}

export function guideTopicText(id: string): string | null {
  const t = guideTopics.find((x) => x.id === id);
  if (!t) return null;
  return `${t.title}\n${t.summary}\n${t.steps.map((s, i) => `${i + 1}. ${s}`).join("\n")}${t.tips ? "\nنصائح:\n" + t.tips.map((s) => `- ${s}`).join("\n") : ""}`;
}
